/* Встроенный каталог: работает без интернета. Команды и навыки написаны для TetraFree и лежат в проекте обычными файлами —
   после установки их можно править. MCP-серверы — настоящие npm-пакеты; запускаются только после «Разрешить». */
import type { McpCfg } from '../lib/mcpconfig'

export type BundledKind = 'skill' | 'command' | 'mcp' | 'bundle'
export interface BundledItem {
  kind: BundledKind
  id: string
  name: string
  desc: string
  /** путь → содержимое (навыки и команды) */
  files?: Record<string, string>
  /** MCP-серверы для записи в .tetra/mcp.json */
  mcp?: Record<string, McpCfg>
  /** что требуется от пользователя */
  notes?: string[]
  /** для наборов: ключи входящих элементов */
  parts?: string[]
}

const cmd = (name: string, description: string, hint: string, body: string): [string, string] => [
  `.tetra/commands/${name}.md`,
  `---\ndescription: ${description}\nargument-hint: ${hint}\n---\n${body.trim()}\n`,
]
const skill = (name: string, description: string, body: string): [string, string] => [
  `.tetra/skills/${name}/SKILL.md`,
  `---\nname: ${name}\ndescription: ${description}\n---\n${body.trim()}\n`,
]
const one = (e: [string, string]) => ({ [e[0]]: e[1] })

