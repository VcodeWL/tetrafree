export const buildBlocks = (k: string): Block[] =>
  (DOC_TEMPLATES.find((t) => t.k === k)?.build() ?? []).map(([type, text, checked]) => ({
    id: uid('b'),
    type,
    text,
    ...(type === 'todo' ? { checked: !!checked } : {}),
  }))
